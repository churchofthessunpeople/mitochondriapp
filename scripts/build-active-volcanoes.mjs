// Builds src/lib/active-volcanoes.data.ts from the Smithsonian Global Volcanism
// Program's Holocene volcano list, keeping volcanoes that erupted since 1800.
// Run: node scripts/build-active-volcanoes.mjs
import { writeFileSync } from "node:fs";

const ACTIVE_SINCE_YEAR = 1800;
const SOURCE_URL =
  "https://webservices.volcano.si.edu/geoserver/GVP-VOTW/ows?service=WFS&version=2.0.0&request=GetFeature&typeName=GVP-VOTW:Smithsonian_VOTW_Holocene_Volcanoes&outputFormat=application/json";
const OUT = new URL("../src/lib/active-volcanoes.data.ts", import.meta.url);

const res = await fetch(SOURCE_URL, { signal: AbortSignal.timeout(60_000) });
if (!res.ok) throw new Error(`GVP request failed: ${res.status}`);
const { features } = await res.json();

const volcanoes = features
  .map(({ properties: p }) => ({
    name: String(p.Volcano_Name).trim(),
    country: String(p.Country ?? "").trim(),
    lat: Number(p.Latitude),
    lng: Number(p.Longitude),
    lastEruptionYear: Number(p.Last_Eruption_Year),
    rock: String(p.Major_Rock_Type ?? "").trim().toLowerCase() || null,
  }))
  .filter(
    (v) =>
      Number.isFinite(v.lat) &&
      Number.isFinite(v.lng) &&
      Number.isFinite(v.lastEruptionYear) &&
      v.lastEruptionYear >= ACTIVE_SINCE_YEAR,
  )
  .sort((a, b) => a.name.localeCompare(b.name));

const today = new Date().toISOString().slice(0, 10);
const body = `/**
 * AUTO-GENERATED by scripts/build-active-volcanoes.mjs on ${today}. Do not edit by hand.
 * Volcanoes that have erupted since ${ACTIVE_SINCE_YEAR}, from the Smithsonian Global
 * Volcanism Program's Holocene volcano list (https://volcano.si.edu/).
 */

import type { ActiveVolcano } from "./active-volcanoes";

export const ACTIVE_SINCE_YEAR = ${ACTIVE_SINCE_YEAR};
export const ACTIVE_VOLCANOES_SNAPSHOT = "${today}";

export const ACTIVE_VOLCANOES: readonly ActiveVolcano[] = ${JSON.stringify(volcanoes, null, 2)};
`;

writeFileSync(OUT, body);
console.log(`active volcanoes ${volcanoes.length} (erupted since ${ACTIVE_SINCE_YEAR})`);
